// "Esere Sor": the backend's source-grounded assistant (POST /api/chat). Answers carry their book sources and may
// contain mistakes; the conversation stays on this screen.
import { Ionicons } from '@expo/vector-icons';
import { useLocalSearchParams } from 'expo-router';
import { useRef, useState } from 'react';
import { ActivityIndicator, FlatList, KeyboardAvoidingView, Platform, Pressable, StyleSheet, Text, TextInput, View } from 'react-native';
import { Notice } from '@/components/UI';
import { askWork, type ChatMode, type ChatTurn } from '@/lib/api';
import { t } from '@/lib/i18n';
import { useContent } from '@/lib/store';
import { colors, space } from '@/lib/theme';

type Message = ChatTurn & { sources?: string[]; failed?: boolean };

export default function Ask() {
  const { slug } = useLocalSearchParams<{ slug: string }>();
  const item = useContent().bySlug(slug);
  const [messages, setMessages] = useState<Message[]>([]);
  const [draft, setDraft] = useState('');
  const [mode, setMode] = useState<ChatMode>('standard');
  const [busy, setBusy] = useState(false);
  const list = useRef<FlatList<Message>>(null);
  const suggestions = [t('Bu eseri kim yaptırdı?', 'Who had this work built?'), t('Ne zaman yapıldı?', 'When was it built?'), t('Mimarisinde neler dikkat çeker?', 'What stands out in its architecture?')];

  async function send(text = draft) {
    const question = text.trim();
    if (question.length < 2 || busy) return;
    const history = messages.filter(m => !m.failed).map(({ role, content }) => ({ role, content }));
    setMessages(m => [...m, { role: 'user', content: question }]);
    setDraft(''); setBusy(true);
    try {
      const r = await askWork(slug, question, mode, history);
      setMessages(m => [...m, { role: 'assistant', content: r.answer, sources: r.sources }]);
    } catch (e) {
      setMessages(m => [...m, { role: 'assistant', content: String((e as Error)?.message ?? e), failed: true }]);
    } finally { setBusy(false); setTimeout(() => list.current?.scrollToEnd({ animated: true }), 50); }
  }

  const modes: [ChatMode, string][] = [['standard', t('Bilgi', 'Facts')], ['story', t('Hikâye', 'Story')], ['child', t('Çocuk', 'Child')]];
  return <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === 'ios' ? 'padding' : undefined} keyboardVerticalOffset={90}>
    <FlatList ref={list} data={messages} keyExtractor={(_, i) => String(i)} contentContainerStyle={{ padding: space.m, gap: space.s + 2 }}
      ListHeaderComponent={<View style={{ gap: space.s, marginBottom: space.s }}>
        <Text style={s.lead}>{item ? t(`${item.name} hakkında sor.`, `Ask about ${item.name}.`) : ''}</Text>
        <Notice>{t('Cevaplar yalnızca envanter kitabına dayanır ve yapay zekâ ile üretilir; hata içerebilir. Kitapta olmayanı "bilgi yok" diye söyler.', 'Answers rely only on the inventory book and are generated by AI; they may contain mistakes. What the book does not say is reported as unknown.')}</Notice>
        <View style={s.row} accessibilityRole="radiogroup">{modes.map(([id, label]) => <Pressable key={id} onPress={() => setMode(id)} accessibilityRole="radio" accessibilityState={{ checked: mode === id }} aria-checked={mode === id} hitSlop={4} style={[s.chip, mode === id && s.chipOn]}>
          <Text style={[s.chipText, mode === id && { color: colors.goldSoft }]}>{label}</Text></Pressable>)}</View>
        {!messages.length && suggestions.map(q => <Pressable key={q} onPress={() => send(q)} style={s.suggestion} accessibilityRole="button"><Text style={s.chipText}>{q}</Text></Pressable>)}
      </View>}
      renderItem={({ item: m }) => <View style={[s.bubble, m.role === 'user' ? s.mine : s.theirs, m.failed && { borderColor: colors.danger }]}>
        <Text style={[s.text, m.role === 'user' && { color: colors.goldSoft }]}>{m.content}</Text>
        {!!m.sources?.length && <Text style={s.sources}>{t('Kaynak: ', 'Source: ')}{m.sources.join(' · ')}</Text>}
      </View>}
      ListFooterComponent={busy ? <View style={[s.bubble, s.theirs, { flexDirection: 'row', gap: 8 }]}><ActivityIndicator color={colors.goldText} /><Text style={s.text}>{t('Kitaba bakılıyor…', 'Checking the book…')}</Text></View> : undefined} />
    <View style={s.composer}>
      <TextInput value={draft} onChangeText={setDraft} placeholder={t('Sorunu yaz', 'Type your question')} placeholderTextColor={colors.soft}
        style={s.input} multiline maxLength={1000} accessibilityLabel={t('Soru', 'Question')} onSubmitEditing={() => send()} />
      <Pressable onPress={() => send()} disabled={busy || draft.trim().length < 2} accessibilityRole="button" accessibilityLabel={t('Gönder', 'Send')}
        style={[s.send, (busy || draft.trim().length < 2) && { opacity: 0.4 }]}><Ionicons name="arrow-up" size={22} color={colors.goldSoft} /></Pressable>
    </View>
  </KeyboardAvoidingView>;
}

const s = StyleSheet.create({
  lead: { color: colors.ink, fontSize: 16 },
  row: { flexDirection: 'row', gap: 6 },
  chip: { minHeight: 40, justifyContent: 'center', paddingHorizontal: 14, paddingVertical: 6, borderRadius: 999, borderWidth: 1, borderColor: colors.goldLine },
  chipOn: { backgroundColor: colors.emerald },
  chipText: { color: colors.ink, fontSize: 14 },
  suggestion: { padding: 12, borderRadius: 12, borderWidth: 1, borderColor: colors.line, backgroundColor: colors.paper },
  bubble: { padding: 12, borderRadius: 14, maxWidth: '88%', borderWidth: 1, gap: 6 },
  mine: { alignSelf: 'flex-end', backgroundColor: colors.emerald, borderColor: colors.emeraldLight },
  theirs: { alignSelf: 'flex-start', backgroundColor: colors.paper, borderColor: colors.line },
  text: { color: colors.ink, fontSize: 15, lineHeight: 22 },
  sources: { color: colors.goldText, fontSize: 12 },
  composer: { flexDirection: 'row', gap: 8, padding: space.s + 2, borderTopWidth: 1, borderTopColor: colors.line, backgroundColor: colors.paper, alignItems: 'flex-end' },
  input: { flex: 1, minHeight: 44, maxHeight: 120, borderRadius: 22, borderWidth: 1, borderColor: colors.goldLine, paddingHorizontal: 16, paddingVertical: 10, color: colors.ink, fontSize: 15 },
  send: { width: 44, height: 44, borderRadius: 22, backgroundColor: colors.emerald, alignItems: 'center', justifyContent: 'center' },
});
